typedef struct { int dummy; } MemoryManager;
static inline void *dcc_brotli_alloc(MemoryManager *m, size_t n) {
    void *p; (void)m; p = malloc(n);
    if (!p) { fputs("Brotli adapter: allocation failed\n", stderr); exit(2); }
    return p;
}
#define BROTLI_ALLOC(M,T,N) ((N)>0 ? (T*)dcc_brotli_alloc((M),(N)*sizeof(T)) : NULL)
#define BROTLI_FREE(M,P) do { (void)(M); free(P); (P)=NULL; } while (0)
#define BROTLI_IS_OOM(M) 0
#define BROTLI_IS_NULL(P) 0
#define BROTLI_ENSURE_CAPACITY(M,T,A,C,R) { \
    if ((C) < (R)) { \
        size_t _new_size = ((C) == 0) ? (R) : (C); T *new_array; \
        while (_new_size < (R)) _new_size *= 2; \
        new_array = BROTLI_ALLOC((M),T,_new_size); \
        if (!BROTLI_IS_OOM(M) && !BROTLI_IS_NULL(new_array) && (C) != 0) \
            memcpy(new_array,(A),(C)*sizeof(T)); \
        BROTLI_FREE((M),A); (A)=new_array; (C)=_new_size; \
    } \
}
/* Layout and comparison rule from upstream cluster.h and cluster.c. */
typedef struct { uint32_t idx1, idx2; double cost_combo, cost_diff; } HistogramPair;
static inline int HistogramPairIsLess(const HistogramPair *p1,const HistogramPair *p2) {
    if (p1->cost_diff != p2->cost_diff) return p1->cost_diff > p2->cost_diff;
    return (p1->idx2-p1->idx1) > (p2->idx2-p2->idx1);
}
