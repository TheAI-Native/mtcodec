static inline double FastLog2(size_t v) {
    return v < 256 ? dcc_log_table[v] : log2((double)v);
}
/* From upstream bit_cost.h, same order of operations. */
static inline double ShannonEntropy(const uint32_t *population, size_t size, size_t *total) {
    size_t sum = 0; double retval = 0;
    const uint32_t *population_end = population + size; size_t p;
    if (size & 1) goto odd_number_of_elements_left;
    while (population < population_end) {
        p = *population++; sum += p; retval -= (double)p * FastLog2(p);
        odd_number_of_elements_left:
        p = *population++; sum += p; retval -= (double)p * FastLog2(p);
    }
    if (sum) retval += (double)sum * FastLog2(sum);
    *total = sum; return retval;
}
static inline double BitsEntropy(const uint32_t *population, size_t size) {
    size_t sum; double retval = ShannonEntropy(population,size,&sum);
    if (retval < (double)sum) retval = (double)sum;
    return retval;
}
